#[test]
fn the_rust_file_has_rgba_constants() {
    let (dir, cx) = project(SAMPLE);
    tokens::run(&all_outputs(), &cx).unwrap();
    let rust = fs::read_to_string(dir.path().join("desktop/tokens.rs")).unwrap();
    assert!(
        rust.starts_with("//! @generated by `rok tools tokens` from tokens.json. Do not edit.\n")
    );
    assert!(rust.contains(
        "pub mod light {\n    /// `oklch(1 0 0)`\n    pub const BACKGROUND: u32 = 0xffffffff;\n"
    ));
    assert!(rust.contains("    pub const CARD_FOREGROUND: u32 = 0x000000ff;\n"));
    assert!(rust.contains("pub mod dark {"));
    assert!(rust.contains("    pub const CHART_1: u32 = 0x00ff0080;\n"));
    assert!(rust.contains("pub const RADIUS: f32 = 10.0;\n"));
    assert!(rust.contains("pub const FONT_HEADING: &str = \"Oxanium Variable\";\n"));
}

#[test]
fn oklch_converts_to_srgb() {
    // the sRGB primaries, as OKLCH
    assert_eq!(
        tokens::parse_color("oklch(0.6279 0.2577 29.23)"),
        Some(0xff0000ff)
    );
    assert_eq!(
        tokens::parse_color("oklch(0.8664 0.2948 142.5)"),
        Some(0x00ff00ff)
    );
    assert_eq!(
        tokens::parse_color("oklch(0.452 0.3132 264.05)"),
        Some(0x0000ffff)
    );
    assert_eq!(
        tokens::parse_color("oklch(50% 0 0deg / 0.5)"),
        Some(0x63636380)
    );
    assert_eq!(tokens::parse_color("#abc"), None);
    assert_eq!(tokens::parse_color("rgb(1 2 3)"), None);
}

#[test]
fn check_passes_when_current_and_fails_on_a_hand_edit() {
    let (dir, cx) = project(SAMPLE);
    let written = tokens::run(&all_outputs(), &cx).unwrap();
    assert!(written.files.iter().all(|f| f.changed));

    let mut check = all_outputs();
    check.check = true;
    let current = tokens::run(&check, &cx).unwrap();
    assert!(Tokens::succeeded(&current));

    let css = dir.path().join("web/tokens.css");
    let edited = fs::read_to_string(&css)
        .unwrap()
        .replace("0.625rem", "1rem");
    fs::write(&css, &edited).unwrap();
    let stale = tokens::run(&check, &cx).unwrap();
    assert!(!Tokens::succeeded(&stale));
    let names: Vec<&str> = stale.stale().map(|f| f.path.as_str()).collect();
    assert_eq!(names, ["web/tokens.css"]);
    assert!(Tokens::to_text(&stale).contains("rok tools tokens"));
    // a check writes nothing
    assert_eq!(fs::read_to_string(&css).unwrap(), edited);
}

#[test]
fn a_missing_output_is_stale() {
    let (_dir, cx) = project(SAMPLE);
    let mut check = all_outputs();
    check.check = true;
    let out = tokens::run(&check, &cx).unwrap();
    assert_eq!(out.stale().count(), 3);
}

#[test]
fn mistakes_name_the_token() {
    let (_dir, cx) = project(
        r##"{"colors": {"light": {"primary": "#000000", "ring": "#000000"}, "dark": {"primary": "#ffffff"}}}"##,
    );
    let error = tokens::run(&all_outputs(), &cx).unwrap_err().to_string();
    assert!(error.contains("colors.dark has no `ring`"), "{error}");

    let (_dir, cx) =
        project(r##"{"colors": {"light": {"primary": "blue"}, "dark": {"primary": "blue"}}}"##);
    let error = tokens::run(&all_outputs(), &cx).unwrap_err().to_string();
    assert!(error.contains("colors.light.primary"), "{error}");

    let (_dir, cx) = project(SAMPLE);
    let error = tokens::run(&TokensOptions::new("tokens.json"), &cx)
        .unwrap_err()
        .to_string();
    assert!(error.contains("no output"), "{error}");
}
